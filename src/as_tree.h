#ifndef IFJ26C_AS_TREE_H
#define IFJ26C_AS_TREE_H

#include "token.h"
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>

/* Node type, selects union members in node */
typedef enum ASTKind_t {
  NODE_PROGRAM,
  NODE_FNDEF,
  NODE_PARAMS,
  NODE_PARAM,
  NODE_BLOCK,
  NODE_ASSIGN,
  NODE_VARDEF,
  NODE_VALDEF,
  NODE_IF,
  NODE_WHILE,
  NODE_RETURN,
  /* expressions */
  NODE_UNOP,
  NODE_BINOP,
  NODE_FNCALL,
  /* lists */
  NODE_ID,
  NODE_INT,
  NODE_DOUBLE,
  NODE_STRING,
  NODE_UNIT,
} ASTKind_t;

/* Data types */
typedef enum DataType_t {
  TYPE_UNKNOWN = 0,
  TYPE_STRING,
  TYPE_DOUBLE,
  TYPE_INT,
  TYPE_UNIT,
  TYPE_BOOLEAN
} DataType_t;

/* Operator types*/
typedef enum Operator_t {
  OP_EQ,
  OP_NEQ,
  OP_LTE,
  OP_LT,
  OP_GTE,
  OP_GT,
  OP_PLUS,
  OP_MINUS,
  OP_UPLUS,
  OP_UMINUS,
  OP_DIV,
  OP_MUL,

  OP_ERR,
} Operator_t;

typedef struct ASTNode_t ASTNode_t;

typedef struct ASTList_t { /* for NODES with variable count (i.e. params...) */
  ASTNode_t **items;
  size_t count;
  size_t capacity;
} ASTList_t;

/*Abstract syntax tree node
 *
 * */
struct ASTNode_t {
  ASTKind_t kind;   /* selects union member */
  DataType_t type;  /* Int, Double, String, Union, Boolean */
  SourceSpan_t pos; /* Position in source code for error handling */

  union {
    char *name;        /* NODE_ID       */
    char *string;      /* NODE_STRING   */
    int intVal;        /* NODE_INT      */
    double dblVal;     /* NODE_DOUBLE   */
    ASTList_t program; /* NODE_PROGRAM  */
    ASTList_t block;   /* NODE_BLOCK    */

    /* NODE_FNDEF, declType may be unknown */
    struct {
      char *name;
      ASTList_t params;
      DataType_t declType;
      ASTNode_t *body;
      bool isMain;
    } fnDef;

    /* NODE_PARAM */
    struct {
      char *name;
      DataType_t declType;
    } param;

    /* NODE_VARDEF and NODE_VALDEF */
    struct {
      char *name;
      DataType_t declType;
      ASTNode_t *init;
    } varDef;

    /* NODE_ASSIGN */
    struct {
      char *name;
      ASTNode_t *value;
    } assign;

    /* NODE_STATEMENT, elseBlock NULL if absent */
    struct {
      ASTNode_t *cond, *thenBlock, *elseBlock;
    } ifElse;

    /* NODE_WHILE */
    struct {
      ASTNode_t *cond, *body;
    } whileDo;

    /* NODE_RETURN, value is NULL if it's empty return */
    struct {
      ASTNode_t *value;
    } ret;

    /* NODE_UNOP */
    struct {
      Operator_t op;
      ASTNode_t *operand;
    } unOp;

    /* NODE_BINOP */
    struct {
      Operator_t op;
      ASTNode_t *left, *right;
    } binOp;

    /* NODE_FNCALL */
    struct {
      char *name;
      ASTList_t args;
    } fncall;
  };
};

/* creates new empty node
 * returns false on memory allocation failure, else true
 */
ASTNode_t *ASTCreate(ASTKind_t kind, SourceSpan_t pos);

/* appends node at the end of list
 * returns false on mem allocation failure, else true
 * does not free on failure
 */
bool ASTAppend(ASTList_t *list, ASTNode_t *node);

/* Frees block allocated for the tree */
void ASTFree(ASTNode_t *node);

/**DEBUG
 * dumps the whole tree in stdout in a pretty way.
 * @note Generated by AI for debugging sanity
 */
void ASTDump(const ASTNode_t *root);

#endif // IFJ26C_AS_TREE_H